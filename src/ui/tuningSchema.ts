import type { SimParams } from "../sim/params";

/** One tunable value: where it lives in SimParams and how the tuning panel shows it. */
export interface TuningField {
  section: keyof SimParams;
  key: string;
  label: string;
  /** "ticks" are shown as seconds (60 ticks = 1 s); "%" values are stored as 0..1; "switch" is 0 (off) or 1 (on). */
  unit: "m/s" | "m/s²" | "m" | "ticks" | "%" | "×" | "/s" | "switch" | "";
  min: number;
  max: number;
  step: number;
  hint?: string;
}

export interface TuningGroup {
  title: string;
  fields: TuningField[];
}

function field<S extends keyof SimParams>(
  section: S,
  key: keyof SimParams[S] & string,
  label: string,
  unit: TuningField["unit"],
  min: number,
  max: number,
  step: number,
  hint?: string,
): TuningField {
  return { section, key, label, unit, min, max, step, hint };
}

